''' when we need to print 3D BODY we are suing open3D libraray  '''
import os
import open3d as o3d

class PersonalizedViewer:
      def __init__(self):
            self.output_folder = os.path.join("output") #path defing 
            
      # display the object file 
      def display(self,filename='personalized_body.obj'):
            obj_path = os.path.join(self.output_folder,filename) #path se value calling
            
            print("="*50)
            print("load personalized human body ....")
            print("="*50)
            
            
            if not os.path.exists(obj_path):
                  raise FileNotFoundError(f"\n obj file does't found {obj_path}")
            
            mesh = o3d.io.read_triangle_mesh(obj_path)
            
            if mesh.is_empty():
                  raise ValueError('mesh is emply')
            
            mesh.compute_vertex_normals()
            print('\n mesh loaded sucesffuly')
            print('vertices : ',len(mesh.vertices))
            print('triangle : ',len(mesh.triangles))
            
            print('\n oening viewer....')
            
            o3d.visualization.draw_geometries(
                  [mesh],
                  window_name = "AI TAILOR SYSTEM - PERSONALIZED HUMAN BODY ",
                  width = 1200,
                  height=800
            )
            print('\n viewer closed \n')
            
            
            
'''testing has been strted '''
if __name__ =='__main__':
      viewer = PersonalizedViewer()
      viewer.display()
                                        
      